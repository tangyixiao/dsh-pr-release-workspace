#!/usr/bin/env node
/**
 * Concatenate `src/client/*.js` into the single browser bundle `lib/client.js`.
 *
 * The Harness loads a plugin's client half as one classic script that calls
 * `window.__ModuleLoader__.load({id, factory})`. There is no bundler in the
 * toolchain and adding one would mean a build dependency for a plugin whose
 * source is already plain ES5-compatible JavaScript. Concatenation is enough:
 * each fragment assigns onto one shared namespace object, and the wrapper is
 * the only thing that must be written exactly once.
 *
 * Fragments are ordered by filename, so the numeric prefixes are load-bearing.
 * `00-head.js` opens the wrapper and `99-tail.js` closes it; both are emitted
 * verbatim so an editor still sees a complete, syntax-highlightable file.
 *
 * @module dsh-pr-release-workspace/scripts/build-client
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const sourceDir = join(root, 'src', 'client')
const outFile = join(root, 'lib', 'client.js')

const files = (await readdir(sourceDir)).filter((name) => name.endsWith('.js')).sort()
if (files.length === 0) {
  console.error('build-client: no fragments in src/client')
  process.exit(1)
}

const parts = ['/* Generated by scripts/build-client.mjs — edit src/client/*.js instead. */']
for (const name of files) {
  const body = await readFile(join(sourceDir, name), 'utf8')
  // A fragment that forgot its trailing newline would glue onto the next one's
  // first line; normalising here keeps the concatenation order-insensitive.
  parts.push(`// ---- src/client/${name} ----`)
  parts.push(body.replace(/\s*$/, ''))
  parts.push('')
}

const bundle = `${parts.join('\n')}\n`
const expectedHead = 'window.__ModuleLoader__.load({'
if (!bundle.includes(expectedHead)) {
  console.error(`build-client: bundle is missing ${expectedHead} — check 00-head.js`)
  process.exit(1)
}
if (!bundle.trimEnd().endsWith('})')) {
  console.error('build-client: bundle does not end with the loader close — check 99-tail.js')
  process.exit(1)
}

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, bundle, 'utf8')
console.log(`build-client: ${files.length} fragments -> lib/client.js (${Buffer.byteLength(bundle)} bytes)`)
